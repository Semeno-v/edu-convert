# --------------------------------------------------------------------------- #
#  Синтетический лист «План» (повторяет структуру реального учебного плана)
# --------------------------------------------------------------------------- #
def _write_plan(path: Path) -> None:
    wb = xlsxwriter.Workbook(str(path))
    ws = wb.add_worksheet("План")

    # Строка 1 (idx 0) — групповые заголовки + «Семестр N» над блоками.
    ws.write(1, 11, "Семестр 1")
    ws.write(1, 21, "Семестр 2")

    # Строка-шапка (idx 2): базовые колонки + 10-колоночные блоки.
    header = {
        0: "Считать в плане", 1: "Индекс", 2: "Наименование",
        3: "Экза мен", 4: "Зачет", 5: "Зачет с оц.",
        6: "Факт", 7: "По плану", 8: "Конт. раб.", 9: "СР", 10: "Конт роль",
        11: "з.е.", 12: "Лек", 13: "Лаб", 14: "Пр", 15: "Конс",
        16: "КаттЗ", 17: "ПО", 18: "СР", 19: "КаттЭ", 20: "Контроль",
        21: "з.е.", 22: "Лек", 23: "Лаб", 24: "Пр", 25: "Конс",
        26: "КаттЗ", 27: "ПО", 28: "СР", 29: "КаттЭ", 30: "Контроль",
        31: "Код", 32: "Наименование", 33: "Компетенции",
    }
    for c, label in header.items():
        ws.write(2, c, label)

    # Раздел-заголовок (должен игнорироваться — индекс не начинается с «Б»).
    ws.write(3, 0, "Обязательная часть")
    ws.write(3, 6, 40)

    # Дисциплина 1: зачёт в семестре 1, читается только в семестре 1.
    d1 = {0: "+", 1: "Б1.О.01", 2: "Методология научных исследований",
          4: 1, 6: 3, 7: 108, 8: 30, 9: 78,
          11: 3, 12: 12, 14: 10, 17: 6, 18: 78,
          31: "01", 32: "Тестовая кафедра", 33: "УК-1-И-1; ПК-2-И-1"}
    for c, v in d1.items():
        ws.write(4, c, v)

    # Дисциплина 2: экзамен в семестре 2, читается в семестре 2.
    d2 = {0: "+", 1: "Б1.В.ДВ.03.01", 2: "Эксплуатация информационных систем",
          3: 2, 6: 6, 7: 216, 8: 51, 9: 105, 10: 60,
          21: 6, 22: 12, 24: 22, 27: 12, 28: 105, 30: 60,
          31: "75", 32: "Кафедра ИС", 33: "ПК-1-И-3; ПК-2-И-1"}
    for c, v in d2.items():
        ws.write(5, c, v)

    wb.close()


@pytest.fixture
def plan_xlsx(tmp_path: Path) -> Path:
    path = tmp_path / "plan.xlsx"
    _write_plan(path)
    return path


# --------------------------------------------------------------------------- #
#  Синтетический исходный РПД (docx)
# --------------------------------------------------------------------------- #
def _write_rpd(path: Path) -> None:
    doc = Document()
    doc.add_paragraph("Федеральное государственное бюджетное образовательное учреждение")
    title = doc.add_paragraph()
    run = title.add_run("Б1.О.01 МЕТОДОЛОГИЯ НАУЧНЫХ ИССЛЕДОВАНИЙ")
    run.bold = True
    doc.add_paragraph("по направлению подготовки 09.04.03 – «Прикладная информатика»")
    doc.add_paragraph("направленности (профиля) «Цифровые технологии»")
    doc.add_paragraph("форма обучения очная")

    # §1 + таблица часов (старые числа для diff)
    doc.add_paragraph("1. Объем дисциплины и виды учебной работы")
    t = doc.add_table(rows=2, cols=5)
    hdr = ["Семестр (курс)", "Форма промежуточной аттестации",
           "Общая трудоемкость часов (ЗЕТ)", "Лекционные занятия, часов",
           "Практические занятия, часов"]
    for c, h in enumerate(hdr):
        t.rows[0].cells[c].text = h
    data = ["1 (1)", "Зачет", "108 (3)", "14", "20"]
    for c, v in enumerate(data):
        t.rows[1].cells[c].text = v

    # §2 компетенции + таблица
    doc.add_paragraph("2. Роль дисциплины в формировании компетенций")
    doc.add_paragraph("Перечень компетенций, необходимых для освоения дисциплины")
    ct = doc.add_table(rows=2, cols=2)
    ct.rows[0].cells[0].text = "Код компетенции"
    ct.rows[0].cells[1].text = "Наименование"
    ct.rows[1].cells[0].text = "УК-1"
    ct.rows[1].cells[1].text = "Способен осуществлять критический анализ"

    # §4 литература
    doc.add_paragraph("4. Учебно-методическое обеспечение дисциплины")
    doc.add_paragraph("4.1.1. Основная литература")
    lit = doc.add_paragraph()
    lit.add_run("Иванов И.И. ").bold = True
    lit.add_run("Методология науки. — М., 2023.")
    doc.add_paragraph("4.1.2. Дополнительная литература")
    doc.add_paragraph("Петров П.П. Дополнительный источник. — СПб., 2022.")

    # §6 ПО
    doc.add_paragraph("6. Программное обеспечение, необходимое для освоения дисциплины")
    doc.add_paragraph("MS Office, Python 3.")

    doc.save(str(path))


